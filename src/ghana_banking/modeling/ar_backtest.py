"""Expanding-window autoregressive forecast benchmark with prediction intervals.

The routine assumes the input is already on a defensible stationary modelling
scale. It does not select transformations or lag order from future data.
"""
from __future__ import annotations

from dataclasses import asdict, dataclass
from typing import List, Sequence

import numpy as np
import pandas as pd
from statsmodels.tsa.ar_model import AutoReg


@dataclass(frozen=True)
class ARBacktestResult:
    """Chronological AR forecasts, intervals and benchmark metrics."""

    variables: List[str]
    lag_order: int
    initial_window: int
    step: int
    horizons: List[int]
    forecast_origins: int
    sample_start: str
    sample_end: str
    forecast_records: List[dict]
    metrics: List[dict]

    def to_dict(self) -> dict:
        return asdict(self)


def _validate_index(index: pd.Index) -> None:
    if isinstance(index, pd.PeriodIndex):
        if index.freq is None:
            raise ValueError("PeriodIndex must have a defined frequency.")
    elif isinstance(index, pd.DatetimeIndex):
        if pd.infer_freq(index) is None:
            raise ValueError("DatetimeIndex must be regular with no missing periods.")
    elif pd.api.types.is_numeric_dtype(index.dtype):
        if len(index) > 2:
            differences = np.diff(np.asarray(index, dtype=float))
            if not np.all(differences == differences[0]):
                raise ValueError("Numeric index must be equally spaced.")
    else:
        raise TypeError("Index must be a regular DatetimeIndex, PeriodIndex or numeric index.")


def expanding_window_ar_backtest(
    data: pd.DataFrame,
    lag_order: int,
    initial_window: int,
    horizons: Sequence[int] = (1, 3, 6),
    step: int = 1,
    trend: str = "c",
    significance_level: float = 0.05,
) -> ARBacktestResult:
    """Backtest one AR model per series using expanding chronological windows.

    At each origin, each univariate AR model is re-estimated using only
    observations available at that origin. Pointwise prediction intervals are
    generated by statsmodels. No-change and expanding historical-mean
    benchmarks are reported alongside the AR forecast.

    All transformations and lag selection must be performed within each
    training window if they are data-driven; this function expects the caller
    to supply an already prepared modelling scale and a prespecified lag.
    """
    if not isinstance(data, pd.DataFrame):
        raise TypeError("data must be a pandas DataFrame.")
    if data.empty or data.shape[1] < 1:
        raise ValueError("data must contain at least one variable and one observation.")
    if not data.columns.is_unique:
        raise ValueError("Variable names must be unique.")
    if data.index.has_duplicates or not data.index.is_monotonic_increasing:
        raise ValueError("Index must be unique and sorted in increasing order.")
    _validate_index(data.index)
    if not all(pd.api.types.is_numeric_dtype(data[c]) for c in data.columns):
        raise TypeError("All variables must be numeric.")
    values = data.to_numpy(dtype=float)
    if not np.isfinite(values).all():
        raise ValueError("Backtest data must be complete and finite.")
    if not isinstance(lag_order, int) or lag_order < 1:
        raise ValueError("lag_order must be a positive integer.")
    if not isinstance(initial_window, int) or initial_window <= lag_order + 2:
        raise ValueError("initial_window must exceed lag_order + 2.")
    if not isinstance(horizons, (list, tuple)) or not horizons:
        raise ValueError("horizons must be a non-empty sequence of positive integers.")
    if any(not isinstance(h, int) or h < 1 for h in horizons):
        raise ValueError("Every forecast horizon must be a positive integer.")
    if len(set(horizons)) != len(horizons):
        raise ValueError("horizons must not contain duplicates.")
    horizon_list = sorted(horizons)
    if not isinstance(step, int) or step < 1:
        raise ValueError("step must be a positive integer.")
    if trend not in {"n", "c", "ct", "ctt"}:
        raise ValueError("trend must be one of 'n', 'c', 'ct', or 'ctt'.")
    if not isinstance(significance_level, (int, float)) or not 0 < significance_level < 1:
        raise ValueError("significance_level must lie strictly between 0 and 1.")
    max_horizon = max(horizon_list)
    if initial_window + max_horizon > len(data):
        raise ValueError("Insufficient observations after initial_window for maximum horizon.")

    records = []
    origins = list(range(initial_window, len(data) - max_horizon + 1, step))
    for origin in origins:
        training = data.iloc[:origin]
        for variable in data.columns:
            series = training[variable].astype(float)
            fitted = AutoReg(series, lags=lag_order, trend=trend, old_names=False).fit()
            prediction = fitted.get_prediction(
                start=origin,
                end=origin + max_horizon - 1,
                dynamic=True,
            ).summary_frame(alpha=float(significance_level))
            no_change = float(series.iloc[-1])
            historical_mean = float(series.mean())
            for horizon in horizon_list:
                target_position = origin + horizon - 1
                actual = float(data.iloc[target_position][variable])
                row = prediction.iloc[horizon - 1]
                records.append({
                    "variable": str(variable),
                    "origin": str(data.index[origin - 1]),
                    "target_date": str(data.index[target_position]),
                    "horizon": int(horizon),
                    "actual": actual,
                    "ar_forecast": float(row["mean"]),
                    "prediction_lower": float(row["mean_ci_lower"]),
                    "prediction_upper": float(row["mean_ci_upper"]),
                    "no_change_forecast": no_change,
                    "expanding_mean_forecast": historical_mean,
                })

    forecast_frame = pd.DataFrame(records)
    metrics = []
    for (variable, horizon), group in forecast_frame.groupby(["variable", "horizon"], sort=False):
        actual = group["actual"].to_numpy(dtype=float)
        row = {"variable": str(variable), "horizon": int(horizon), "n_forecasts": int(len(group))}
        for name, forecast_col in (
            ("ar", "ar_forecast"),
            ("no_change", "no_change_forecast"),
            ("expanding_mean", "expanding_mean_forecast"),
        ):
            errors = actual - group[forecast_col].to_numpy(dtype=float)
            row[f"{name}_mae"] = float(np.mean(np.abs(errors)))
            row[f"{name}_rmse"] = float(np.sqrt(np.mean(errors ** 2)))
        row["ar_interval_coverage"] = float(np.mean(
            (actual >= group["prediction_lower"].to_numpy(dtype=float))
            & (actual <= group["prediction_upper"].to_numpy(dtype=float))
        ))
        row["ar_mean_interval_width"] = float(np.mean(
            group["prediction_upper"].to_numpy(dtype=float)
            - group["prediction_lower"].to_numpy(dtype=float)
        ))
        metrics.append(row)

    return ARBacktestResult(
        variables=[str(column) for column in data.columns],
        lag_order=lag_order,
        initial_window=initial_window,
        step=step,
        horizons=[int(h) for h in horizon_list],
        forecast_origins=len(origins),
        sample_start=str(data.index[0]),
        sample_end=str(data.index[-1]),
        forecast_records=records,
        metrics=metrics,
    )
